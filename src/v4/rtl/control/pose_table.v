// 模块：动作数据表（pose_table）
// 作用：按动作编号和目标区域，输出6个关节的示例位置。
// 输入：动作编号pose_id、目标区域region。
// 输出：6个位置打包数据、运动时间。
// 注意：所有位置都是例子，真实机械臂必须先标定。
// 阅读：每行右侧说明这行代码在做什么。

`timescale 1ns / 1ps // 仿真时间单位1ns，最小精度1ps；不产生硬件时钟。
module pose_table #( // 定义这个模块；括号中写参数或输入输出接口。
    parameter integer MOVE_MS = 800 // 设置动作等待毫秒数；这些常量在综合前确定。
) ( // 结束参数列表，开始写输入输出接口。
    input  wire [ 2:0] pose_id, // 声明接口：动作编号。
    input  wire [ 1:0] region, // 声明接口：目标区域。
    output reg  [95:0] positions, // 声明接口：6个关节打包位置。
    output reg  [15:0] duration_ms // 声明接口：运动时间。
); // 结束输入输出接口定义。
    reg [15:0] j1; // 声明16位寄存器：第1关节位置。
    reg [15:0] j2; // 声明16位寄存器：第2关节位置。
    reg [15:0] j3; // 声明16位寄存器：第3关节位置。
    reg [15:0] j4; // 声明16位寄存器：第4关节位置。
    reg [15:0] j5; // 声明16位寄存器：第5关节位置。
    reg [15:0] j6; // 声明16位寄存器：夹爪位置。
    always @* begin // 输入一变就重新计算，下面是组合逻辑。
        j1 = 1500; // 第1关节位置设为1500。
        j2 = 1500; // 第2关节位置设为1500。
        j3 = 1500; // 第3关节位置设为1500。
        j4 = 1500; // 第4关节位置设为1500。
        j5 = 1500; // 第5关节位置设为1500。
        j6 = 1500; // 夹爪位置设为1500。
        duration_ms = MOVE_MS; // 运动时间设为动作等待毫秒数。
        if (region == 0) j1 = 1300; // 判断目标区域等于0；第1关节位置设为1300。
        else if (region == 2) j1 = 1700; // 判断目标区域等于2；第1关节位置设为1700。
        case (pose_id) // 根据动作编号，选择6个关节的位置。
            0: begin // 处于0时执行；开始该步骤。
                j1 = 1500; // 第1关节位置设为1500。
            end // 结束当前代码块。
            1: begin // 处于1时执行；开始该步骤。
                j2 = 1400; // 第2关节位置设为1400。
                j3 = 1600; // 第3关节位置设为1600。
                j6 = 1700; // 夹爪位置设为1700。
            end // 结束当前代码块。
            2: begin // 处于2时执行；开始该步骤。
                j2 = 1400; // 第2关节位置设为1400。
                j3 = 1600; // 第3关节位置设为1600。
                j6 = 1300; // 夹爪位置设为1300。
            end // 结束当前代码块。
            3: begin // 处于3时执行；开始该步骤。
                j2 = 1550; // 第2关节位置设为1550。
                j3 = 1450; // 第3关节位置设为1450。
                j6 = 1300; // 夹爪位置设为1300。
            end // 结束当前代码块。
            4: begin // 处于4时执行；开始该步骤。
                j1 = 1800; // 第1关节位置设为1800。
                j2 = 1450; // 第2关节位置设为1450。
                j6 = 1300; // 夹爪位置设为1300。
            end // 结束当前代码块。
            5: begin // 处于5时执行；开始该步骤。
                j1 = 1800; // 第1关节位置设为1800。
                j2 = 1450; // 第2关节位置设为1450。
                j6 = 1700; // 夹爪位置设为1700。
            end // 结束当前代码块。
            default: begin // 处于default时执行；开始该步骤。
                j1 = 1500; // 第1关节位置设为1500。
            end // 结束当前代码块。
        endcase // 结束状态或编号分支。
        positions = {j6, j5, j4, j3, j2, j1}; // 把6个位置拼成96位，最低16位是第1关节。
    end // 结束当前代码块。
endmodule // 本模块结束。
